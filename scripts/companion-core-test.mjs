import assert from "node:assert/strict";
import { build } from "esbuild";
import { pathToFileURL } from "node:url";
await build({ entryPoints: ["lib/server/freeAnswerAce.ts"], outfile: ".eval-out/companion-identity.cjs", bundle: true, platform: "node", format: "cjs" });
const identity = (await import(pathToFileURL(`${process.cwd()}/.eval-out/companion-identity.cjs`))).default;
process.env.REQUEST_CONTROL_HMAC_SECRET = "test-only-not-production-".repeat(3);
const now = 1790000000000;
const token = identity.issueFreeIdentity(now);
const subject = identity.verifyFreeIdentity(token, now);
assert.match(subject, /^[a-f0-9]{64}$/);
assert.equal(identity.verifyFreeIdentity(token, now + 365 * 86400000), subject);
assert.equal(identity.verifyFreeIdentity(token, now + 367 * 86400000), null);
assert.equal(identity.verifyFreeIdentity(token, now - 120000), null);
assert.equal(identity.verifyFreeIdentity(token.slice(0, -1) + (token.endsWith("a") ? "b" : "a"), now), null);
assert.equal(identity.verifyFreeIdentity(null, now), null);
assert.equal(identity.verifyFreeIdentity("x".repeat(10000), now), null);
assert.notEqual(identity.verifyFreeIdentity(identity.issueFreeIdentity(now), now), subject);
delete process.env.REQUEST_CONTROL_HMAC_SECRET;
assert.throws(() => identity.issueFreeIdentity(now));
console.log("PASS: identity signature, expiry, tampering, invalid inputs, unique subjects, fail-closed configuration");
await build({ entryPoints: ["lib/server/boundedBody.ts"], outfile: ".eval-out/companion-body.cjs", bundle: true, platform: "node", format: "cjs" });
const body = (await import(pathToFileURL(`${process.cwd()}/.eval-out/companion-body.cjs`))).default;
const request = text => new Request("https://example.invalid/", { method: "POST", body: text });
assert.equal(await body.readBoundedText(request("한글"), 6), "한글");
await assert.rejects(() => body.readBoundedText(request("한글"), 5), body.BodyTooLargeError);
await assert.rejects(() => body.readBoundedText(request("x".repeat(513)), 512), body.BodyTooLargeError);
console.log("PASS: request byte limits, exact Unicode boundary, oversized stream rejection");
